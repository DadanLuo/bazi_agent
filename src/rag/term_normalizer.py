def _remove_connectors(text: str) -> str:
    """
    移除连接词，如"与"、"和"等
    
    Examples:
        "吉与凶" -> "吉凶"
        "强与弱" -> "强弱"
    """
    # 移除"与"字连接
    text = text.replace("与", "")
    # 移除"和"字连接
    text = text.replace("和", "")
    return text


def _normalize_compound_terms(text: str) -> str:
    """
    标准化复合术语
    
    处理常见的复合词模式，如：
    - "XX格" -> "XX"（如果XX本身是标准术语）
    """
    # 处理"XX格"模式
    ge_patterns = [
        ("正财格", "正财"),
        ("偏财格", "偏财"),
        ("正官格", "正官"),
        ("偏官格", "偏官"),
        ("正印格", "正印"),
        ("偏印格", "偏印"),
        ("比肩格", "比肩"),
        ("劫财格", "劫财"),
        ("食神格", "食神"),
        ("伤官格", "伤官"),
        ("建禄格", "建禄"),
        ("羊刃格", "羊刃"),
    ]
    
    for pattern, replacement in ge_patterns:
        text = text.replace(pattern, replacement)
    
    return text


def normalize(text: str) -> str:
    """
    标准化术语
    
    处理流程：
    1. 先处理复合术语
    2. 移除连接词
    3. 应用核心术语映射
    
    Args:
        text: 待标准化的文本
        
    Returns:
        标准化后的文本
    """
    return get_domain_lexicon().normalize_text(text)


def get_variant_mapping() -> Dict[str, str]:
    """获取变体词映射"""
    mapping = TERM_VARIANTS.copy()
    mapping.update(get_domain_lexicon().alias_to_canonical)
    return mapping


def get_standard_terms() -> Set[str]:
    """获取所有标准术语"""
    return KEEP_ORIGINAL | set(get_domain_lexicon().terms)


def is_standard_term(term: str) -> bool:
    """检查是否为标准术语"""
    return term in get_standard_terms()


def extract_terms(text: str) -> List[str]:
    """
    从文本中提取命理术语
    
    Args:
        text: 输入文本
        
    Returns:
        提取到的术语列表
    """
    return get_domain_lexicon().canonical_terms(text)
